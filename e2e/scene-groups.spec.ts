import { expect, test } from '@playwright/test';
import { fileURLToPath } from 'node:url';
import { openAdventure } from './start-helpers';

test('Pointlesh scene groups organize items and expose add, visibility, and lock controls', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const fixture = fileURLToPath(new URL('./scene-groups-fixture.ts', import.meta.url));
  await page.route('**/scene-groups-fixture', route => route.fulfill({ contentType: 'text/html', body: `<!doctype html><html><body><script type="module" src="/@fs${fixture}"></script></body></html>` }));
  await page.goto('/scene-groups-fixture');
  const groups = page.locator('.pointlesh-scene-groups');
  const background = groups.locator('section.pointlesh-scene-group[aria-label="Background"]');
  await expect(background.getByText('background.village', { exact: true })).toBeVisible();
  await expect(background.getByRole('button', { name: 'Add background' })).toHaveCount(0);
  await background.getByRole('button', { name: 'Hide background' }).click();
  expect(await page.evaluate(() => (window as any).sceneGroupsFixture.designer.getManifest().scenes.village.pointleshBackground.visible)).toBe(false);
  await background.getByRole('button', { name: 'Show background' }).click();
  await background.getByRole('button', { name: 'Lock background' }).click();
  await expect(background.getByRole('button', { name: 'Unlock background' })).toBeVisible();
  await expect(background.getByRole('button', { name: 'Unlock background' })).toHaveAttribute('data-locked', 'true');
  await expect(background.getByRole('button', { name: 'Unlock background' })).toContainText('Locked');
  await expect(background.getByRole('button', { name: 'Edit background' })).toBeDisabled();
  await background.getByRole('button', { name: 'Unlock background' }).click();
  await expect(background.getByRole('button', { name: 'Lock background' })).toHaveAttribute('data-locked', 'false');
  await background.getByRole('button', { name: 'Edit background' }).click();
  const picker = page.getByRole('dialog', { name: 'Edit background' }).getByRole('button', { name: 'Background image asset' });
  const search = page.getByRole('dialog', { name: 'Edit background' }).getByRole('combobox', { name: 'Search background image asset' });
  await expect(search).toBeHidden();
  await picker.click();
  await expect(search).toBeVisible();
  await search.fill('forest');
  await expect(page.getByRole('dialog', { name: 'Edit background' }).getByRole('option')).toHaveCount(1);
  await page.getByRole('dialog', { name: 'Edit background' }).getByRole('option', { name: 'background.forest' }).click();
  await expect(search).toBeHidden();
  await expect(picker).toContainText('background.forest');
  await page.getByRole('dialog', { name: 'Edit background' }).getByRole('button', { name: 'Apply' }).click();
  await expect(background.getByText('background.forest', { exact: true })).toBeVisible();
  for (const [title, kind] of [['Characters', 'character'], ['Objects', 'object'], ['Points', 'point'], ['Areas', 'area'], ['Hotspots', 'hotspot']]) {
    const section = groups.locator(`section.pointlesh-scene-group[aria-label="${title}"]`);
    await expect(section).toBeVisible();
    await expect(section.getByRole('button', { name: `Add ${kind}`, exact: true })).toBeVisible();
  }
  await expect(groups.getByText('Copper Tankard door · outside', { exact: true })).toHaveCount(1);
  await expect(groups.locator('.scene-designer__subhead').getByText('Copper Tankard door · outside', { exact: true })).toHaveCount(0);
  const characters = groups.locator('section.pointlesh-scene-group[aria-label="Characters"]');
  await characters.getByRole('button', { name: 'Hide characters' }).click();
  expect(await page.evaluate(() => (window as any).sceneGroupsFixture.designer.getManifest().scenes.village.layers[0].prefabs[0].visible)).toBe(false);
  await characters.getByRole('button', { name: 'Show characters' }).click();
  await characters.getByRole('button', { name: 'Lock characters' }).click();
  await expect(characters.getByRole('button', { name: 'Unlock characters' })).toBeVisible();
  await characters.getByRole('button', { name: 'Unlock characters' }).click();
  await groups.getByRole('button', { name: 'Add point', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Add point' });
  await expect(dialog.getByRole('combobox', { name: 'Choose point' })).toBeVisible();
  await dialog.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(groups.locator('section.pointlesh-scene-group[aria-label="Points"] .scene-designer__item')).toHaveCount(2);
  await groups.getByRole('button', { name: 'Add point', exact: true }).click();
  const newPoint = page.getByRole('dialog', { name: 'Add point' });
  await newPoint.getByRole('combobox', { name: 'Choose point' }).selectOption('__new__');
  await newPoint.getByRole('textbox', { name: 'New point name' }).fill('Far entrance');
  await newPoint.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(groups.locator('section.pointlesh-scene-group[aria-label="Points"] .scene-designer__item')).toHaveCount(3);
  await expect(groups.getByText('Far entrance', { exact: true })).toBeVisible();
  await groups.getByRole('button', { name: 'Add object', exact: true }).click();
  const newObject = page.getByRole('dialog', { name: 'Add object' });
  await expect(newObject.getByRole('combobox', { name: 'Choose object' })).toHaveValue('__new__');
  await newObject.getByRole('textbox', { name: 'New object name' }).fill('Local prop');
  await newObject.getByRole('button', { name: 'Add', exact: true }).click();
  const local = await page.evaluate(() => {
    const manifest = (window as any).sceneGroupsFixture.designer.getManifest();
    const instance = manifest.scenes.village.layers[0].prefabs.find((item: any) => item.name === 'Local prop');
    return manifest.prefabs[instance.prefabId].pointlesh.editor.sceneLocal;
  });
  expect(local).toBe(true);
  await groups.getByRole('button', { name: 'Add area', exact: true }).click();
  const areaDialog = page.getByRole('dialog', { name: 'New area' });
  await areaDialog.getByRole('textbox', { name: 'Name' }).fill('New floor');
  await areaDialog.getByRole('button', { name: 'Draw shape' }).click();
  await expect(groups.locator('section.pointlesh-scene-group[aria-label="Areas"] .scene-designer__item')).toHaveCount(2);
  await groups.getByRole('button', { name: 'Add hotspot', exact: true }).click();
  const hotspotDialog = page.getByRole('dialog', { name: 'New hotspot' });
  await hotspotDialog.getByRole('textbox', { name: 'Name' }).fill('New clue');
  await hotspotDialog.getByRole('button', { name: 'Draw shape' }).click();
  await expect(groups.locator('section.pointlesh-scene-group[aria-label="Hotspots"] .scene-designer__item')).toHaveCount(2);
  expect(errors).toEqual([]);
});

test('scene item controls keep the scenes panel at the same scroll position', async ({ page }) => {
  const fixture = fileURLToPath(new URL('./scene-groups-fixture.ts', import.meta.url));
  await page.route('**/scene-groups-fixture', route => route.fulfill({ contentType: 'text/html', body: `<!doctype html><html><body><script type="module" src="/@fs${fixture}"></script></body></html>` }));
  await page.goto('/scene-groups-fixture');
  const result = await page.evaluate(() => {
    const panel = document.querySelector<HTMLElement>('.scene-designer__panel[data-panel="scenes"]')!;
    panel.style.maxHeight = '180px';
    panel.scrollTop = panel.scrollHeight;
    const before = panel.scrollTop;
    panel.querySelector<HTMLButtonElement>('[aria-label="Lock Copper Tankard door · outside"]')!.click();
    const afterLock = panel.scrollTop;
    panel.querySelector<HTMLButtonElement>('[aria-label="Hide Copper Tankard door · outside"]')!.click();
    return { before, afterLock, afterHide: panel.scrollTop };
  });
  expect(result.before).toBeGreaterThan(0);
  expect(result.afterLock).toBe(result.before);
  expect(result.afterHide).toBe(result.before);
});

test('the demo exposes its real room background and restores it after editor hiding', async ({ page }) => {
  await openAdventure(page, true);
  await expect(page.locator('#loading')).toBeHidden({ timeout: 60000 });
  const background = page.locator('section.pointlesh-scene-group[aria-label="Background"]');
  await expect(background.getByText('background.village-pub', { exact: true })).toBeVisible();
  await background.getByRole('button', { name: 'Hide background' }).click();
  expect(await page.evaluate(() => (window as any).pointleshDemo.scene.background.visible)).toBe(false);
  await page.getByRole('button', { name: 'Toggle scene designer' }).click();
  expect(await page.evaluate(() => (window as any).pointleshDemo.scene.background.visible)).toBe(true);
});
